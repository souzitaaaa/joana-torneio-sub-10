-- =====================================================================
-- 6. Sincronizar as sequências das identity columns
-- Como inserimos ids explícitos acima (overriding system value), as
-- sequências internas ainda não sabem que esses números já estão
-- ocupados. Isto garante que o próximo INSERT sem id explícito continua
-- a partir do valor certo, em vez de tentar repetir o id 1.
-- =====================================================================

select setval(pg_get_serial_sequence('equipas', 'id'),       (select max(id) from equipas));
select setval(pg_get_serial_sequence('jogos', 'id'),         (select max(id) from jogos));
select setval(pg_get_serial_sequence('jogadores', 'id'),     (select max(id) from jogadores));
select setval(pg_get_serial_sequence('patrocinadores', 'id'),(select max(id) from patrocinadores));


-- =====================================================================
-- 7. ROW LEVEL SECURITY
-- Leitura pública (o site é público), escrita fechada por agora — só o
-- service_role (usado no backend/admin, nunca no browser) pode escrever.
-- Quando tiveres um painel de admin com login, troca a policy de escrita
-- para `to authenticated` com a condição que fizer sentido.
-- =====================================================================

alter table fases               enable row level security;
alter table campos               enable row level security;
alter table tiers_patrocinador   enable row level security;
alter table equipas              enable row level security;
alter table jogos                enable row level security;
alter table jogadores            enable row level security;
alter table patrocinadores       enable row level security;

create policy "leitura publica" on fases               for select using (true);
create policy "leitura publica" on campos               for select using (true);
create policy "leitura publica" on tiers_patrocinador   for select using (true);
create policy "leitura publica" on equipas              for select using (true);
create policy "leitura publica" on jogos                for select using (true);
create policy "leitura publica" on jogadores            for select using (true);
create policy "leitura publica" on patrocinadores       for select using (true);

