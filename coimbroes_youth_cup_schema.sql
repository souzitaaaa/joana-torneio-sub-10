-- 3. JOGOS
-- =====================================================================

create table if not exists jogos (
    id               bigint generated by default as identity primary key,
    fase             text not null references fases(code),
    campo            smallint not null references campos(numero),
    hora             time not null,

    -- Jogos de grupo: equipa_casa_id/equipa_fora_id preenchidos (id direto).
    equipa_casa_id   bigint references equipas(id),
    equipa_fora_id   bigint references equipas(id),

    -- Jogos da fase final, ANTES de o grupo respetivo terminar: em vez de
    -- um id direto, guarda-se a "seed" (posição no grupo). Equivalente a
    -- { grupo: "A", posicao: 1 } em data.js — resolvido em runtime pela
    -- mesma lógica de resolverSeed()/resolverEquipaJogo() em stats.js.
    seed_casa_grupo    char(1) check (seed_casa_grupo in ('A', 'B', 'C')),
    seed_casa_posicao  smallint check (seed_casa_posicao between 1 and 3),
    seed_fora_grupo    char(1) check (seed_fora_grupo in ('A', 'B', 'C')),
    seed_fora_posicao  smallint check (seed_fora_posicao between 1 and 3),

    golos_casa       smallint,
    golos_fora       smallint,
    estado           text not null default 'agendado'
                       check (estado in ('agendado', 'a_decorrer', 'terminado')),
    minuto           smallint,   -- minuto ao vivo, só relevante quando estado = 'a_decorrer'

    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now(),

    -- Cada lado tem de vir preenchido de UMA forma só: id direto OU seed,
    -- nunca as duas nem nenhuma.
    constraint jogos_lado_casa_valido check (
        (equipa_casa_id is not null and seed_casa_grupo is null and seed_casa_posicao is null)
        or
        (equipa_casa_id is null and seed_casa_grupo is not null and seed_casa_posicao is not null)
    ),
    constraint jogos_lado_fora_valido check (
        (equipa_fora_id is not null and seed_fora_grupo is null and seed_fora_posicao is null)
        or
        (equipa_fora_id is null and seed_fora_grupo is not null and seed_fora_posicao is not null)
    )
);

comment on table jogos is 'Equivalente a JOGOS em data.js.';

create index if not exists idx_jogos_fase   on jogos (fase);
create index if not exists idx_jogos_estado on jogos (estado);

-- Mantém updated_at sempre correto sem teres de o definir à mão em cada UPDATE.
create or replace function set_updated_at()
returns trigger as $$
begin
    new.updated_at = now();
    return new;
end;
$$ language plpgsql;

drop trigger if exists trg_jogos_updated_at on jogos;
create trigger trg_jogos_updated_at
    before update on jogos
    for each row execute function set_updated_at();

