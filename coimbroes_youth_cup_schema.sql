-- 4. JOGADORES
-- =====================================================================

create table if not exists jogadores (
    id         bigint generated by default as identity primary key,
    equipa_id  bigint not null references equipas(id) on delete cascade,
    numero     smallint not null,
    nome       text not null,
    created_at timestamptz not null default now(),
    unique (equipa_id, numero)   -- duas camisolas iguais na mesma equipa não fazem sentido
);

comment on table jogadores is
    'Equivalente a JOGADORES em data.js. Nomes ainda são placeholders '
    '("Jogador N") — substitui pelos nomes reais só depois de teres '
    'autorização dos encarregados de educação (dados de menores, sub-10).';

-- Gera os mesmos 10 jogadores-placeholder por equipa que gerarPlantelPlaceholder()
-- fazia em JS, com o mesmo esquema de id (equipa_id * 100 + numero).
insert into jogadores (id, equipa_id, numero, nome)
select
    e.id * 100 + n as id,
    e.id           as equipa_id,
    n              as numero,
    'Jogador ' || n as nome
from equipas e
cross join generate_series(1, 10) as n
on conflict (id) do nothing;


